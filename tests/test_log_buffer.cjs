const assert=require('node:assert/strict');
const LogBuffer=require('../web/log-buffer.js');
const item=id=>({id,at:id,kind:'rx',frame:'00'});
const buffer=new LogBuffer(3);
buffer.accept({items:[item(1),item(2)],cursor:2});
buffer.pause();
const frozen=JSON.stringify(buffer.view);
buffer.accept({items:[item(3),item(4),item(5)],cursor:5});
assert.equal(JSON.stringify(buffer.view),frozen);
assert.equal(buffer.pending,3);
assert.deepEqual(buffer.rows.map(x=>x.id),[3,4,5]);
buffer.resume();assert.deepEqual(buffer.view.map(x=>x.id),[3,4,5]);
const oldGeneration=buffer.generation;
buffer.clear(5);
assert.equal(buffer.accept({items:[item(4)],cursor:4},oldGeneration),false);
buffer.accept({items:[item(6)],cursor:6});
assert.deepEqual(buffer.view.map(x=>x.id),[6]);
buffer.accept({items:[item(6)],cursor:6});assert.equal(buffer.rows.length,1);
console.log('Log history: frozen scroll snapshot, bounded buffer, resume, clear race and deduplication passed.');
